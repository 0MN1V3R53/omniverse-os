def generate_from_csv_url():
    """Download ZIP coordinates from a public dataset."""
    import urllib.request

    url = "https://gist.githubusercontent.com/erichurst/7882666/raw/5bdc46db47d9515269ab12ed6fb2850377fd869e/US%2520Zip%2520Codes%2520from%25202013%2520Government%2520Data"
    print(f"Downloading ZIP coordinate data from {url}...")

    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        response = urllib.request.urlopen(req, timeout=30)
        raw = response.read().decode("utf-8")
    except Exception as e:
        print(f"Download failed: {e}")
        print("Falling back to built-in major ZIP prefix dataset...")
        return generate_prefix_fallback()

    reader = csv.DictReader(io.StringIO(raw))
    zip_data = {}
    for row in reader:
        zipcode = (row.get("ZIP") or "").strip()
        lat = row.get("LAT") or ""
        lon = row.get("LNG") or ""
        if zipcode and lat and lon:
            # Ensure ZIP codes are always 5 digits with leading zeros
            zipcode = zipcode.zfill(5)
            try:
                zip_data[zipcode] = {
                    "lat": round(float(lat), 6),
                    "lon": round(float(lon), 6)
                }
            except ValueError:
                continue

    print(f"Parsed {len(zip_data)} ZIP codes from CSV")
    return zip_data


def generate_prefix_fallback():
    """
    Generate a comprehensive ZIP coordinate database using Python's zipfile
    data from free-zipcode-data or embedded prefix mapping.
    We'll build from a secondary source.
    """
    import urllib.request

    # Try simplemaps free US ZIP code database
    url2 = "https://simplemaps.com/static/data/us-zips/1.90/basic/simplemaps_uszips_basicv1.90.zip"
    # Alternative: use the federally published ZCTA data
    url3 = "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_zcta_national.txt"

    print(f"Trying Census Bureau ZCTA gazetteer: {url3}")
    try:
        req = urllib.request.Request(url3, headers={"User-Agent": "Mozilla/5.0"})
        response = urllib.request.urlopen(req, timeout=30)
        raw = response.read().decode("utf-8")
        lines = raw.strip().split("\n")
        zip_data = {}
        for line in lines[1:]:  # Skip header
            parts = line.split("\t")
            if len(parts) >= 8:
                zipcode = parts[0].strip()
                try:
                    lat = float(parts[5].strip())
                    lon = float(parts[6].strip())
                    zip_data[zipcode] = {"lat": round(lat, 6), "lon": round(lon, 6)}
                except (ValueError, IndexError):
                    continue
        print(f"Parsed {len(zip_data)} ZIP codes from Census ZCTA gazetteer")
        return zip_data
    except Exception as e:
        print(f"Census download also failed: {e}")
        print("Using embedded major city ZIP dataset...")
        return generate_embedded_dataset()


